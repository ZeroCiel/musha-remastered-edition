def parse_ldt_header(data):
    """解析LDT文件头 (复制自ldt_writer.py以避免导入依赖)"""
    unk = struct.unpack('<I', data[0:4])[0]
    col_count = struct.unpack('<I', data[4:8])[0]
    row_count = struct.unpack('<I', data[8:12])[0]

    col_names = []
    for i in range(col_count):
        offset = 12 + i * 64
        name_bytes = data[offset:offset+64]
        name = name_bytes.split(b'\x00')[0].decode('ascii', errors='replace').strip()
        col_names.append(name)

    col_types = []
    for i in range(col_count):
        offset = 8204 + i * 4
        t = struct.unpack('<I', data[offset:offset+4])[0]
        col_types.append(t)

    return {
        'col_count': col_count,
        'row_count': row_count,
        'col_names': ['_RowId'] + col_names,
        'col_types': [3] + col_types,
        'data_start': 8716,
    }


def read_rows(data, header):
    """读取所有行"""
    rows = []
    pos = header['data_start']
    types = header['col_types']

    for _ in range(header['row_count']):
        row = []
        for t in types:
            if pos + 4 > len(data):
                break
            if t == 0:
                val = struct.unpack('<I', data[pos:pos+4])[0]
                row.append(str(val))
                pos += 4
            elif t == 3:
                val = struct.unpack('<i', data[pos:pos+4])[0]
                row.append(str(val))
                pos += 4
            elif t == 2:
                val = struct.unpack('<I', data[pos:pos+4])[0]
                row.append('true' if val else 'false')
                pos += 4
            elif t == 4:
                val = struct.unpack('<f', data[pos:pos+4])[0]
                row.append(str(val))
                pos += 4
            elif t == 1:
                if pos + 2 > len(data):
                    break
                str_len = struct.unpack('<H', data[pos:pos+2])[0]
                pos += 2
                if str_len > 0 and pos + str_len <= len(data):
                    try:
                        s = data[pos:pos+str_len].decode('gbk', errors='replace')
                    except:
                        s = data[pos:pos+str_len].decode('utf-8', errors='replace')
                    row.append(s)
                    pos += str_len
                else:
                    row.append('')
            else:
                row.append('0')
                pos += 4
        rows.append(row)

    return rows


def build_ldt(header, rows, orig_data):
    """从表数据重建LDT二进制"""
    buf = bytearray()

    # 文件头
    buf.extend(orig_data[:12])

    # 列名区
    for i in range(header['col_count']):
        offset = 12 + i * 64
        buf.extend(orig_data[offset:offset+64])

    # 填充到8204
    name_end = 12 + header['col_count'] * 64
    buf.extend(orig_data[name_end:8204])

    # 类型定义
    for i in range(header['col_count']):
        offset = 8204 + i * 4
        buf.extend(orig_data[offset:offset+4])

    # 填充到8716
    type_end = 8204 + header['col_count'] * 4
    buf.extend(orig_data[type_end:8716])

    # 写入数据行
    row_count = 0
    types = header['col_types']
    rows_written = 0

    for row in rows:
        if len(row) != len(types):
            continue

        for col_idx, val in enumerate(row):
            t = types[col_idx]
            try:
                if t == 0:
                    buf.extend(struct.pack('<I', int(val) if val else 0))
                elif t == 3:
                    buf.extend(struct.pack('<i', int(val) if val else 0))
                elif t == 2:
                    buf.extend(struct.pack('<I', 1 if val.lower() in ('true', '1') else 0))
                elif t == 4:
                    buf.extend(struct.pack('<f', float(val) if val else 0.0))
                elif t == 1:
                    if val:
                        gbk = val.encode('gbk', errors='replace')
                        buf.extend(struct.pack('<H', len(gbk)))
                        buf.extend(gbk)
                    else:
                        buf.extend(struct.pack('<H', 0))
            except Exception as e:
                print(f"  行{rows_written} 列{col_idx}: 值={val} 类型={t} 错误={e}")
                if t == 1:
                    buf.extend(struct.pack('<H', 0))
                else:
                    buf.extend(struct.pack('<i', 0))

        rows_written += 1

    # 更新行数
    struct.pack_into('<I', buf, 8, rows_written)

    return bytes(buf)


def convert_file(filepath):
    """转换单个LDT文件的繁体字为简体"""
    with open(filepath, 'rb') as f:
        data = f.read()

    if len(data) < 12:
        return False, 0

    try:
        header = parse_ldt_header(data)
    except:
        return False, 0

    # 如果没有任何string类型列，跳过
    if 1 not in header['col_types']:
        return False, 0

    rows = read_rows(data, header)

    # 统计有多少处替换
    total_replacements = 0

    for ri, row in enumerate(rows):
        for ci, t in enumerate(header['col_types']):
            if t == 1 and row[ci]:
                val = row[ci]
                new_val = ''
                replaced = 0
                for ch in val:
                    if ch in T2S:
                        new_val += T2S[ch]
                        replaced += 1
                    else:
                        new_val += ch
                if replaced > 0:
                    rows[ri][ci] = new_val
                    total_replacements += replaced

    if total_replacements == 0:
        return False, 0

    # 备份原文件
    bak_path = filepath + BAK_SUFFIX
    if not os.path.exists(bak_path):
        shutil.copy2(filepath, bak_path)

    # 重建并写入
    new_data = build_ldt(header, rows, data)
    with open(filepath, 'wb') as f:
        f.write(new_data)

    return True, total_replacements


def main():
    ldt_files = sorted(glob.glob(os.path.join(LDT_DIR, '*.LDT')))
    # 排除备份文件
    ldt_files = [f for f in ldt_files if not f.endswith('.bak') and 'bak_' not in f]

    total_files = 0
    total_replacements = 0

    print(f"扫描 {len(ldt_files)} 个LDT文件...")
    print()

    for i, filepath in enumerate(ldt_files):
        fname = os.path.basename(filepath)
        ok, count = convert_file(filepath)
        if ok:
            total_files += 1
            total_replacements += count
        print(f"  [{i+1:3d}/{len(ldt_files)}] {fname:40s} {'✓' if ok else '-'} {f'({count}处替换)' if ok else ''}")

    print()
    print(f"=== 完成 ===")
    print(f"  处理文件: {total_files}/{len(ldt_files)}")
    print(f"  总替换: {total_replacements} 处")
    print(f"  备份后缀: {BAK_SUFFIX}")


if __name__ == '__main__':
    main()
